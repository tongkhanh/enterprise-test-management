import assert from 'node:assert/strict'
import React from 'react'
import { renderToString } from 'react-dom/server'
import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { MemoryRouter } from 'react-router-dom'
import { createServer } from 'vite'
globalThis.localStorage = { getItem: () => null, setItem: () => {}, removeItem: () => {} }
const server = await createServer({ server: { middlewareMode: true, watch: null }, appType: 'custom', logLevel: 'error' })
const queryClient = new QueryClient({ defaultOptions: { queries: { retry: false, gcTime: 0 } } })
try {
  const { default: QAWorkflow } = await server.ssrLoadModule('/src/features/e2e/QAWorkflow.jsx')
  const { GitHubForm } = await server.ssrLoadModule('/src/features/e2e/E2EStudioPage.jsx')
  const { default: AutomationLabPage } = await server.ssrLoadModule('/src/features/automation/AutomationLabPage.jsx')
  const query = { data: [], isPending: false, isError: false, refetch() {} }
  const mutation = { isPending: false, mutate() {} }
  const profile = { name: 'FoodRush', environment: '', baseUrl: '', allowedHosts: '', roles: '', testData: '{}', seedUrl: '', cleanupUrl: '' }
  const props = { activeStep: 'profile', setActiveStep() {}, activeProject: 'project-a', projects: { data: [{ _id: 'project-a', key: 'QA', name: 'Example' }] }, setProject() {}, profiles: query, profile, profileMode: 'GitHubE2E', setProfile() {}, setProfileMode() {}, currentProfile: null, createProfile: mutation, updateProfile: mutation, environments: query, integrations: query, github: [], git: { integrationId: 'missing', repository: 'owner/repo', ref: 'main', paths: 'README.md' }, setGit() {}, analyzeGithub: mutation, newProfile() {}, selectProfile() {}, useCases: query, useCase: {}, setUseCase() {}, suggestUseCases: mutation, addUseCase: mutation, approveUseCase: mutation, generateStory: mutation, currentStories: [], suites: query, createSuite: mutation, generateCases: mutation, currentCases: [], plans: query, StoryDraftCard: () => null, TestCaseStep: () => null, GitHubForm }
  const render = (element) => renderToString(React.createElement(QueryClientProvider, { client: queryClient }, React.createElement(MemoryRouter, null, element)))
  const html = render(React.createElement(QAWorkflow, props))
  assert.match(html.replace(/<!-- -->/g, ''), /Giai đoạn 1\/4 · Bước 1\/12/)
  assert.match(html, /Nguồn &amp; yêu cầu/)
  assert.match(html, /Thiết kế &amp; lập Sprint/)
  assert.match(html, /Chuẩn bị &amp; chạy/)
  assert.match(html, /Kết quả/)
  assert.match(html, /aria-label="Các bước: Nguồn &amp; yêu cầu"/)
  assert.equal((html.match(/aria-current="step"/g) || []).length, 1)
  assert.equal((html.match(/aria-pressed="true"/g) || []).length, 2, 'One phase and one source must be selected')
  assert.doesNotMatch(html, /flex overflow-x-auto border-t p-2/)
  assert.match(html, /Chưa có Profile trong project này/)
  assert.match(html, /Project chưa có kết nối GitHub đã kiểm tra/)
  assert.match(html, /Thêm hoặc kiểm tra kết nối GitHub/)
  assert.match(html, /profileName=FoodRush/)
  assert.doesNotMatch(html, /2\. Repository/)
  assert.doesNotMatch(html, /<option value="">Tạo Profile mới<\/option>/)
  const manual = render(React.createElement(QAWorkflow, { ...props, profileMode: 'SystemProfile' }))
  assert.match(manual, /Chưa cần URL hoặc môi trường chạy/)
  assert.match(manual, /Mô tả hệ thống và phạm vi kiểm thử/)
  const createButton = manual.match(/<button[^>]*>Tạo Profile<\/button>/)?.[0]
  assert.ok(createButton, 'Manual source must offer profile creation')
  assert.doesNotMatch(createButton, /\sdisabled(?:=|\s|>)/)
  assert.match(createButton, /from-violet-800/)
  assert.match(manual, /motion-safe:hover:-translate-y-0\.5/)
  assert.match(manual, /motion-reduce:transition-none/)
  const emptyName = render(React.createElement(QAWorkflow, { ...props, profileMode: 'SystemProfile', profile: { ...profile, name: '' } }))
  assert.match(emptyName.match(/<button[^>]*>Tạo Profile<\/button>/)?.[0] || '', /\sdisabled(?:=|\s|>)/)
  assert.doesNotMatch(manual, /Môi trường chạy \(không bắt buộc\)/)
  const approved = render(React.createElement(QAWorkflow, { ...props, profileMode: 'SystemProfile', currentProfile: { _id: 'profile-a', name: 'FoodRush' }, useCases: { ...query, data: [{ _id: 'uc-a', status: 'Approved' }] }, currentStories: [{ _id: 'story-a', approvalStatus: 'Approved' }] }))
  assert.equal((approved.match(/Có mục đã duyệt/g) || []).length, 2, 'Only actual approved items are labelled as approved')
  const runtime = render(React.createElement(QAWorkflow, { ...props, activeStep: 'runtime', currentProfile: { _id: 'profile-a', name: 'FoodRush', project: 'project-a' } }))
  assert.match(runtime.replace(/<!-- -->/g, ''), /Giai đoạn 3\/4 · Bước 9\/12/)
  assert.match(runtime, /aria-label="Các bước: Chuẩn bị &amp; chạy"/)
  assert.equal((runtime.match(/aria-current="step"/g) || []).length, 1)
  assert.match(runtime, /Chưa có môi trường sẵn sàng/)
  assert.match(runtime, /Tạo hoặc kiểm tra môi trường tại đây/)
  assert.match(runtime, /returnProfile=profile-a/)
  const embedded = render(React.createElement(AutomationLabPage, { embedded: true, initialProject: 'project-a', onEnvironmentReady() {} }))
  assert.match(embedded, /Dùng website có sẵn/)
  assert.match(embedded, /Dựng từ GitHub \+ Docker/)
  assert.doesNotMatch(embedded, /Lộ trình thực thi/)
  assert.doesNotMatch(embedded, /Multi-engine Script Generator/)
  const profileError = render(React.createElement(QAWorkflow, { ...props, profiles: { ...query, isError: true } }))
  assert.match(profileError, /Không tải được Profile của project/)
  assert.match(profileError, /Thử tải lại/)
  const runtimeError = render(React.createElement(QAWorkflow, { ...props, environments: { ...query, isError: true }, activeStep: 'runtime', currentProfile: { _id: 'profile-a', name: 'FoodRush', project: 'project-a' } }))
  assert.match(runtimeError, /Không tải được/)
  const integration = { _id: 'connection-a', displayName: 'Team GitHub', provider: 'GitHub', status: 'Connected' }
  queryClient.setQueryData(['e2e-github-repositories', 'connection-a'], { pages: [{ items: [{ id: 1, fullName: 'owner/repo', defaultBranch: 'main' }], page: 1, hasMore: false }], pageParams: [1] })
  queryClient.setQueryData(['e2e-github-branches', 'connection-a', 'owner/repo'], [{ name: 'main' }])
  queryClient.setQueryData(['e2e-github-commits', 'connection-a', 'owner/repo', 'main'], [])
  queryClient.setQueryData(['e2e-github-pulls', 'connection-a', 'owner/repo'], [])
  queryClient.setQueryData(['e2e-github-source-files', 'connection-a', 'owner/repo', 'main'], { items: [{ path: 'README.md', size: 100 }, ...Array.from({ length: 1000 }, (_, index) => ({ path: `src/file-${String(index).padStart(4, '0')}.js`, size: 100 }))], total: 1001, truncated: false })
  const connected = render(React.createElement(QAWorkflow, { ...props, github: [integration], git: { ...props.git, integrationId: 'connection-a' } }))
  assert.match(connected, /Team GitHub/)
  assert.match(connected, /owner\/repo/)
  assert.doesNotMatch(connected, /Project chưa có kết nối GitHub đã kiểm tra/)
  assert.match(connected, /1001<!-- --> tệp phù hợp/)
  assert.match(connected, /Tìm tệp theo tên hoặc đường dẫn/)
  assert.match(connected, /Chọn tệp gợi ý/)
  assert.match(connected, /Tôi cho phép gửi nội dung hoặc trích đoạn/)
  assert.doesNotMatch(connected, /src\/file-0999\.js/, 'Large repositories render only the current page')
  assert.match(connected, /disabled=""[^>]*><svg[^>]*[^]*?Phân tích nguồn và tạo Profile/)
  const noRepository = render(React.createElement(QAWorkflow, { ...props, github: [integration], git: { ...props.git, integrationId: 'connection-a', repository: '', paths: '' } }))
  assert.match(noRepository, /Chọn repository trước/)
  console.log('E2E onboarding: empty, error and connected states render with actionable guidance.')
} finally { queryClient.clear(); await server.close() }
