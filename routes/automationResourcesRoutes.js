const router = require('express').Router();
const c = require('../controllers/automationResourcesController');
const { protect } = require('../middleware/auth');
const { asyncHandler } = require('../middleware/error');
router.use(protect);
router.get('/automation-datasets', asyncHandler(c.datasetList));
router.post('/automation-datasets', asyncHandler(c.datasetCreate));
router.get('/automation-datasets/:id/preview', asyncHandler(c.datasetPreview));
router.get('/automation-fixtures', asyncHandler(c.fixtureList));
router.post('/automation-fixtures', asyncHandler(c.fixtureCreate));
router.post('/automation-batches', asyncHandler(c.batch));
router.get('/automation-schedules', asyncHandler(c.scheduleList));
router.post('/automation-schedules', asyncHandler(c.scheduleCreate));
router.patch('/automation-schedules/:id', asyncHandler(c.scheduleUpdate));
router.post('/automation-schedules/:id/trigger', asyncHandler(c.scheduleTrigger));
router.get('/automation-flaky', asyncHandler(c.flaky));
router.patch('/automation-flaky/:id', asyncHandler(c.quarantine));
router.get('/traceability', asyncHandler(c.traceability));
router.get('/automation-operations', asyncHandler(c.operations));
router.post('/automation-queues/:queue/:id/retry', asyncHandler(c.retryJob));
router.get('/metrics', asyncHandler(c.metrics));
module.exports = router;
